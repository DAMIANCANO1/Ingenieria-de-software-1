   //definir un metodo de moldeara la tabla para presentar los datos 
   //en la ventana 
   
   public void mostrarDatos(){
       //definir el modelo basico para la tabla 
       DefaultTableModel miTabla = new DefaultTableModel();
       
       //agregar encabezados al modelo basico
       miTabla.addColumn("NOMBRE");
       miTabla.addColumn("AP");
       miTabla.addColumn("AM");
       miTabla.addColumn("TELEFONO");
       miTabla.addColumn("CORREO");
       miTabla.addColumn("EDO CIV");
       miTabla.addColumn("HIJOS");
       miTabla.addColumn("INTERESES");
       
       
       //definir variables para recbir cada 
       //datos que se traiga de cada registro en la BD
       
       String nombre ="";
       String ap ="";
       String am ="";
       String telefono ="";
       String correo ="";
       String estado_civil ="";
       int hijos = 0;
       String intereses ="";
       
       //definir un arreglo tipo objet para
       //colocar todos los datos por cada registro
       
       Object arr[] = new Object[8];
       
       //colocar el modelo de tabla con encabezados
       //en la tabla de la ventana 
       
       tablaUsuarios.setModel(miTabla);
       
       //preparar y ejecutar la consulta para obtener los datos
       //desde la base de datos 
       //definir a consulta mediante una variable
       String sql = "SELECT * from empleados";
        try {
            //extablecer la apertura de la basde de datos
            Statement st = cn.createStatement();
            //ejecutar la consulta 
            ResultSet rs = st.executeQuery(sql);
            
            //Recorrer la informacion obtenida 
            //para depurarla y conformar cada
            //registro para su presentacion
            
            while (rs.next()) {
                //Tomar cada dato obtenido para guardarlo en su
                //respectiva posicion y conformar los registros
                //a presentar en la ventana 
                
                arr[0] = nombre = rs.getString(2);
                arr[1] = ap = rs.getString(3);
                arr[2] = am = rs.getString(4);
                arr[3] = telefono = rs.getString(5);
                arr[4] = correo = rs.getString(6);
                arr[5] = estado_civil = rs.getString(7);
                arr[6] = hijos = rs.getInt(8);
                arr[7] = intereses = rs.getString(9);
                
                //anadir el registro que se acaba de confromar 
                miTabla.addRow(arr);
            
                
            }
            //tabla completa de regristros a la tabla grafica 
            //de la ventana 
            
            tablaUsuarios.setModel(miTabla);
            
        } catch (SQLException ex) {
            System.getLogger(mostrarUsuarios.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
       
       
   }

