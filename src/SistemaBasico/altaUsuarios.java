    //crear metodo que captura los datos del formulario
    //y los lleva a guardar a la base de datos 
    public void capturaGuardaDatos() {
        //capturar toda la informacion desde el formulario 
        String nombre = campoNombre.getText();
        String ap = campoAp.getText();
        String am = CampoApMat.getText();
        String telefono = campoTelefono.getText();
        String email = campoEmail.getText();
        String estado_civil = menuEC.getSelectedItem().toString();

        int hijos = 0;
        if (radioSi.isSelected()) {
            hijos = 1;
        } else if (radioNo.isSelected()) {
            hijos = 0;
        }

        String intereses = "";
        if (checkLibros.isSelected()) {
            intereses += "Libros";

        }
        if (checkMusica.isSelected()) {
            intereses += "Musica";

        }
        if (checkDeportes.isSelected()) {
            intereses += "Deportes";

        }
        if (checkOtros.isSelected()) {
            intereses += "Otros";

        }
        //preparar la consulta para guardar los datos en BD

        PreparedStatement pps;
        try {
            pps = cn.prepareStatement("INSERT INTO empleados (nombre, apellidop, apellidom, telefono, correo, estado_civil, hijos, intereses) VALUES (?,?,?,?,?,?,?,?)");
            pps.setString(1, nombre);
            pps.setString(2, ap);
            pps.setString(3, am);
            pps.setString(4, telefono);
            pps.setString(5, email);
            pps.setString(6, estado_civil);
            pps.setInt(7, hijos);
            pps.setString(8, intereses);
            
            //ejecutar la consulta
            pps.executeUpdate();
            
            //4 imprimir un mensaje de exito
            JOptionPane.showMessageDialog(null, "DATOS GUARDADOS CON EXITO");
            limpiaCampos();
        } catch (SQLException ex) {
            System.getLogger(altaUsuarios.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    }
    
